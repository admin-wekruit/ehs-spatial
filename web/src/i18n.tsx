const Context = createContext<{
  language: Language;
  setLanguage: (v: Language) => void;
  t: (key: string) => string;
}>({ language: "zh", setLanguage: () => {}, t: (key) => key });
export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setValue] = useState<Language>(() =>
    localStorage.getItem("panoptes.language") === "en" ? "en" : "zh",
  );
  const setLanguage = (next: Language) => {
    localStorage.setItem("panoptes.language", next);
    setValue(next);
    document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
  };
  const t = (key: string) => messages[key]?.[language === "zh" ? 0 : 1] || key;
  return (
    <Context.Provider value={{ language, setLanguage, t }}>
      {children}
    </Context.Provider>
  );
}
export const useI18n = () => useContext(Context);
